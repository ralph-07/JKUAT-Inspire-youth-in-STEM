# Loops are and essential part of programming. They allow you to repeat a block of code multiple times.
# There are two types of loops in Python: for and while.

# For loop
# A for loop is used for iterating over a sequence (a list, a tuple, a dictionary, a set, or a string).
# Let use iterate over a list
fruits = ["apple", "banana", "cherry","pineapple"]

for fruit in fruits:
    print(fruit)

    for i in range(10):
        print(i)

    for i in range(7):
        print(i)

    for char in "Ralph":
        print(char)

    